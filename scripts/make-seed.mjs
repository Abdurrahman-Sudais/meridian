// Generates supabase/seed.sql from the catalogue in config.js.
// Usage:  node scripts/make-seed.mjs
// Re-run whenever you change config.js, then paste seed.sql into the Supabase SQL editor.
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

const root = new URL('..', import.meta.url);
const src = readFileSync(new URL('config.js', root), 'utf8');

// config.js is a browser script — give it the few globals it touches.
const ctx = { location: { search: '' }, localStorage: { getItem: () => null }, URLSearchParams };
vm.createContext(ctx);
vm.runInContext(src + '\n;globalThis.__STORE = STORE;', ctx);
const store = ctx.__STORE;

const q = s => s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`;
const rows = store.products.map(p => {
  const { id, name, cat, price, stock = 1, ...rest } = p;
  return `(${id}, ${q(name)}, ${q(cat)}, ${Number(price).toFixed(2)}, ${stock}, true, ${q(JSON.stringify(rest))}::jsonb)`;
});

const sql = `-- Generated by scripts/make-seed.mjs from config.js — do not edit by hand.
insert into products (id, name, cat, price_usd, stock, active, data) values
${rows.join(',\n')}
on conflict (id) do update set
  name = excluded.name, cat = excluded.cat, price_usd = excluded.price_usd,
  data = excluded.data, active = excluded.active, updated_at = now();
-- Note: stock is only set for NEW products; existing stock is left alone so sales aren't undone.

insert into promo_codes (code, percent) values
('HERITAGE5', 5), ('COLLECTOR10', 10)
on conflict (code) do nothing;
`;
writeFileSync(new URL('supabase/seed.sql', root), sql);
console.log(`Wrote supabase/seed.sql with ${rows.length} products.`);
